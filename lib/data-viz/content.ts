import curriculumJson from "@/content/data-viz/curriculum.json";
import editorialJson from "@/content/data-viz/editorial.json";
import pagesJson from "@/content/data-viz/pages.json";
import type { Block, Chapter, Curriculum, Lesson, SourcePage } from "@/lib/data-viz/types";

const pages = pagesJson as SourcePage[];
const curriculum = curriculumJson as Curriculum;

export const SOURCE_PAGES: readonly SourcePage[] = pages;
export const PAGE_BY_SLUG = new Map(pages.map((page) => [page.slug, page]));
export const CHAPTERS: readonly Chapter[] = curriculum.chapters;
export const LESSONS: readonly Lesson[] = curriculum.lessons;
export const CHAPTER_BY_NUMBER = new Map(CHAPTERS.map((chapter) => [chapter.number, chapter]));
export const LESSON_BY_KEY = new Map(LESSONS.map((lesson) => [`${lesson.section}:${lesson.slug}`, lesson]));

export const CURRICULUM_SOURCE = curriculum.source;

export const EnglishLessons = LESSONS.filter((lesson) => lesson.section === "en");
export const ArabicLessons = LESSONS.filter((lesson) => lesson.section === "ar");

export function lessonHref(lesson: Lesson): string {
  return lesson.section === "ar" ? `/learn/ar/${lesson.slug}` : `/learn/${lesson.slug}`;
}

export function chapterHref(chapter: Chapter): string {
  return `/learn/chapter/${chapter.number}`;
}

export function getChapter(number: string): Chapter | undefined {
  return CHAPTER_BY_NUMBER.get(number);
}

export function getLesson(slug: string, section: "en" | "ar" = "en"): Lesson | undefined {
  return LESSON_BY_KEY.get(`${section}:${slug}`);
}

export function getSourcePage(lesson: Lesson): SourcePage | undefined {
  return lesson.source ? PAGE_BY_SLUG.get(lesson.source) : undefined;
}

const EDITORIAL = editorialJson as Record<string, Block[]>;

/** Source blocks for a lesson: the imported page, or the labelled editorial body. */
export function getLessonBlocks(lesson: Lesson): { blocks: Block[]; direction: "ltr" | "rtl" } | null {
  const page = getSourcePage(lesson);
  if (page) return { blocks: page.blocks, direction: page.direction };
  const blocks = EDITORIAL[lesson.slug];
  if (blocks) return { blocks, direction: "ltr" };
  return null;
}

export function hasEditorialBody(slug: string): boolean {
  return Boolean(EDITORIAL[slug]);
}

export function lessonsForChapter(chapter: Chapter): Lesson[] {
  return chapter.lessons
    .map((slug) => {
      const lesson =
        LESSONS.find((item) => item.slug === slug && item.section === "en") ??
        LESSONS.find((item) => item.slug === slug);
      return lesson;
    })
    .filter((lesson): lesson is Lesson => Boolean(lesson))
    .sort((a, b) => (a.section === b.section ? 0 : a.section === "en" ? -1 : 1));
}

/** Lessons in reading order for one language path, across chapter boundaries. */
export function orderedLessons(section: "en" | "ar"): Lesson[] {
  const standalone = LESSONS.filter((lesson) => lesson.section === section && lesson.chapter === null);
  return [
    ...standalone,
    ...CHAPTERS.flatMap((chapter) =>
      chapter.lessons
        .map((slug) => LESSONS.find((item) => item.slug === slug && item.section === section))
        .filter((lesson): lesson is Lesson => Boolean(lesson)),
    ),
  ];
}

export function adjacentLessons(lesson: Lesson): { previous: Lesson | null; next: Lesson | null } {
  const siblings = orderedLessons(lesson.section);
  const index = siblings.findIndex((item) => item.slug === lesson.slug);
  return {
    previous: index > 0 ? siblings[index - 1] : null,
    next: index >= 0 && index < siblings.length - 1 ? siblings[index + 1] : null,
  };
}

export function adjacentChapters(chapter: Chapter): { previous: Chapter | null; next: Chapter | null } {
  const index = CHAPTERS.findIndex((item) => item.number === chapter.number);
  return {
    previous: index > 0 ? CHAPTERS[index - 1] : null,
    next: index >= 0 && index < CHAPTERS.length - 1 ? CHAPTERS[index + 1] : null,
  };
}

export function lessonPathForSource(sourceSlug: string): string | null {
  const lesson = LESSONS.find((item) => item.source === sourceSlug);
  return lesson ? lessonHref(lesson) : null;
}

export function routeForPageLink(slug: string | null | undefined): string | null {
  if (!slug) return null;
  const lesson = LESSONS.find((item) => item.source === slug);
  return lesson ? lessonHref(lesson) : null;
}

/** English lessons are statically generated by `/learn/[slug]`. */
export function englishStaticParams() {
  return EnglishLessons.map((lesson) => ({ slug: lesson.slug }));
}

/** Arabic companion lessons are generated by `/learn/ar/[slug]`. */
export function arabicStaticParams() {
  return ArabicLessons.map((lesson) => ({ slug: lesson.slug }));
}

export function chapterStaticParams() {
  return CHAPTERS.map((chapter) => ({ number: chapter.number }));
}

export const SOURCE_STATS = {
  pages: pages.length,
  englishPages: pages.filter((page) => page.lang === "en").length,
  arabicPages: pages.filter((page) => page.lang === "ar").length,
  textCharacters: pages.reduce((sum, page) => sum + page.textLength, 0),
  figures: pages.reduce((sum, page) => sum + page.counts.figures, 0),
  uniqueFigures: (() => {
    const files = new Set<string>();
    const visit = (blocks: Block[]) => {
      for (const block of blocks) {
        if (block.type === "figure" && block.asset?.file) files.add(block.asset.file);
        if (block.type === "callout" || block.type === "toggle") visit(block.blocks);
      }
    };
    for (const page of pages) visit(page.blocks);
    return files.size;
  })(),
  tables: pages.reduce((sum, page) => sum + page.counts.tables, 0),
  coveredLessons: LESSONS.filter((lesson) => lesson.coverage === "COVERED").length,
  editorialLessons: LESSONS.filter((lesson) => lesson.kind === "editorial").length,
};
