// The single build-time day ledger for the timeline Home and the day/detail
// routes. It starts from the fail-closed dated feed and appends the explicit
// editorial placements from the owner's bank. Import this module everywhere
// the editorial timeline is rendered; do not rebuild the boundary per route.
import insightsContent from "@/content/knowledge/insights.json";
import insightBank from "@/docs/daily-insight-bank-20261106/INSIGHT_BANK.json";
import questionRelease from "@/content/knowledge/question-insights.json";
import { getDays } from "./day-ledger";
import { adaptBankRecord, buildEditorialDays, type EditorialBankRecord } from "./editorial-days";
import {
  DAILY_HISTORY_START,
  LIVE_DAILY_START,
  liveDailyGroup,
  shuffleDailyBank,
  type LiveDecks,
} from "./daily-bank";
import type { Insight } from "./insights";
import { QUESTION_INSIGHT_ID, QUESTION_INSIGHT_STATUS } from "./question-insights";

export const EDITORIAL_DAYS = buildEditorialDays(
  getDays(insightsContent.items as Insight[], true),
  insightBank.items as EditorialBankRecord[],
);

// The 2026-11-06 authoring bank fed every live edition before the question
// release. Those dates are frozen: their three records are computed here, at
// build time, so existing links (?date=…&insight=…) keep resolving and the
// client never receives the 400-record bank.
const LEGACY_LIVE_DECK = shuffleDailyBank(
  "hansa-insight-bank-2026-11-06",
  (insightBank.items as EditorialBankRecord[])
    .filter(record =>
      record.sourceReviewed === true &&
      (record.reviewStatus === "draft" || record.reviewStatus === "technical_review") &&
      record.lessonHref?.startsWith("/") && !record.lessonHref.startsWith("//") &&
      !(record.reviewStatus === "draft" && record.publicationApproved === true),
    )
    .map(record => adaptBankRecord(record, LIVE_DAILY_START)),
);

if (LEGACY_LIVE_DECK.length < 6) {
  throw new Error("Live daily insights require at least six source-reviewed bank records.");
}

// Question-derived release (PRODUCT.md §6a). Generated by
// scripts/build-question-insights.mjs; every record is checked again here so a
// hand edit to the JSON cannot slip an unlabelled or foreign record through.
function checkedRelease(items: Insight[], label: string): Insight[] {
  const seen = new Set<string>();
  for (const item of items) {
    if (!QUESTION_INSIGHT_ID.test(item.id) || seen.has(item.id)) throw new Error(`${label}: bad or duplicate id ${item.id}`);
    if (item.reviewStatus !== QUESTION_INSIGHT_STATUS) throw new Error(`${label}: ${item.id} has status ${item.reviewStatus}`);
    if (!item.lessonHref.startsWith("/") || !item.practiceHref.startsWith("/")) throw new Error(`${label}: ${item.id} has a non-local link`);
    if (!item.questionIds.length || !item.takeaway || !item.caveat || !item.scenario) throw new Error(`${label}: ${item.id} is incomplete`);
    seen.add(item.id);
  }
  return items;
}

const QUESTION_START = questionRelease.startsOn;
if (!/^\d{4}-\d{2}-\d{2}$/.test(QUESTION_START) || QUESTION_START <= DAILY_HISTORY_START) {
  throw new Error(`Question insight release has an invalid start date: ${QUESTION_START}`);
}
const primary = checkedRelease(questionRelease.primary as Insight[], "primary");
const secondary = checkedRelease(questionRelease.secondary as Insight[], "secondary");
if (primary.length < 2 || primary.length % 2 !== 0 || secondary.length < 1) {
  throw new Error("Question insight release needs an even primary deck and a non-empty secondary deck.");
}

function legacyEditions(): Record<string, Insight[]> {
  const editions: Record<string, Insight[]> = {};
  const date = new Date(DAILY_HISTORY_START + "T00:00:00Z");
  for (let stamp = DAILY_HISTORY_START; stamp < QUESTION_START; stamp = date.toISOString().slice(0, 10)) {
    editions[stamp] = liveDailyGroup(LEGACY_LIVE_DECK, stamp).map(insight => ({ ...insight, date: stamp }));
    date.setUTCDate(date.getUTCDate() + 1);
  }
  return editions;
}

export const LIVE_DECKS: LiveDecks<Insight> = {
  legacy: legacyEditions(),
  primary: shuffleDailyBank(questionRelease.version, primary),
  secondary: shuffleDailyBank(`${questionRelease.version}/secondary`, secondary),
  startsOn: QUESTION_START,
};
