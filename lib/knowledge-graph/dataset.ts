import { getAtlasPublic } from "@/lib/atlas/server";
import editorial from "@/content/atlas/editorial.json";
import extension from "@/content/atlas/dp600-extension.json";
import continuation from "@/content/atlas/dp600-continuation.json";
import { curriculum } from "@/lib/curriculum/model";
import { buildGraphSource } from "./build";
import { analyseGraph, candidateEdges, islandLabel } from "./analyse";
import { forceLayout } from "./layout";
import type { GraphDiagnostic, GraphNode, GraphStats, KnowledgeGraph } from "./types";

const PALETTE = [
  "#4C7DF0", "#E06C75", "#2AA889", "#C678DD", "#D9A21B", "#5BA85A", "#D1785B", "#3FA7D6",
  "#B45BD1", "#7C9A2C", "#E0559B", "#28A5A5", "#8B7BE8", "#C9882E", "#4E9E6A", "#D45D5D",
  "#5C8FE0", "#A97FD6", "#6EA23C", "#D07AA8",
];

function round(value: number) {
  return Math.round(value * 10) / 10;
}

let cached: KnowledgeGraph | undefined;

/**
 * Builds the whole graph from the registries. Memoised per process; the route
 * uses the serialized result from `public/graph/dataset.json`, generated by
 * `npm run graph:build`.
 */
export function buildKnowledgeGraph(): KnowledgeGraph {
  if (cached) return cached;
  const source = buildGraphSource();
  const diagnostics: GraphDiagnostic[] = [...source.diagnostics];
  const candidates = candidateEdges(source.units);
  const edges = [...source.edges, ...candidates];

  // The analysed graph is what a reader sees by default: content units plus the
  // documents they cite, linked by declared citations and prerequisites. Container
  // membership and the co-citation projection are layers, not the base graph.
  const contentIds = source.nodes
    .filter((node) => node.kind === "unit" || node.kind === "source" || node.kind === "page")
    .map((node) => node.id);
  const analysis = analyseGraph(contentIds, source.edges);

  const unitIds = new Set(source.units.map((unit) => unit.id));
  const containerLabel = new Map(source.nodes.filter((node) => node.kind !== "unit").map((node) => [node.id, node.label]));

  const islandOfUnit = new Map<number, GraphNode[]>();
  for (const node of source.nodes) {
    if (node.kind !== "unit") {
      node.island = analysis.componentOf.get(node.id);
      continue;
    }
    node.island = analysis.componentOf.get(node.id);
    const list = islandOfUnit.get(node.island ?? -1) ?? [];
    list.push(node);
    islandOfUnit.set(node.island ?? -1, list);
  }

  // Islands with no other member are not a discovered structure; they stay
  // neutral (island -1) so the map does not invent a one-note cluster.
  const islandSizes = new Map<number, number>();
  for (const node of source.nodes) {
    if (node.kind === "unit" && node.island !== undefined) islandSizes.set(node.island, (islandSizes.get(node.island) ?? 0) + 1);
  }
  const normaliseIsland = (id: number | undefined) => {
    if (id === undefined) return -1;
    return (islandSizes.get(id) ?? 0) < 2 ? -1 : id;
  };

  const subjectLabel = new Map(curriculum().subjects.map((subject) => [subject.id as string, subject.title as string]));
  const islands: KnowledgeGraph["islands"] = {};
  let islandRank = 0;
  for (const [id, members] of [...islandOfUnit.entries()].sort((a, b) => b[1].length - a[1].length || a[0] - b[0])) {
    const { label, subjects } = islandLabel(
      members,
      (containerId) => containerLabel.get(containerId) ?? containerId,
      (subjectId) => subjectLabel.get(subjectId) ?? subjectId,
    );
    islands[id] = {
      label,
      size: members.length,
      subjects,
      color: id === -1 ? "#8A8F98" : PALETTE[islandRank++ % PALETTE.length],
    };
  }
  // Relabel single-member islands as neutral.
  for (const node of source.nodes) {
    if (node.kind === "unit") node.island = normaliseIsland(node.island);
    else node.island = undefined;
  }

  // Visual weight: citations, source-page derivation and prerequisites. A
  // membership edge alone does not make a note heavier.
  const displayDegree = new Map<string, number>();
  for (const edge of source.edges) {
    if (edge.kind === "contains" || edge.kind === "co-citation" || edge.kind === "lexical") continue;
    displayDegree.set(edge.from, (displayDegree.get(edge.from) ?? 0) + 1);
    displayDegree.set(edge.to, (displayDegree.get(edge.to) ?? 0) + 1);
  }
  for (const node of source.nodes) node.degree = displayDegree.get(node.id) ?? 0;

  // One deterministic layout over the base knowledge graph. Candidates and
  // containers never influence geometry; containers take a centroid at runtime.
  const layoutNodes = source.nodes.filter((node) => node.kind === "unit" || node.kind === "source" || node.kind === "page");
  const layoutNodeIds = new Set(layoutNodes.map((node) => node.id));
  const layout = forceLayout(
    layoutNodes.map((node) => ({
      id: node.id,
      community: node.island ?? 0,
      weight: node.kind === "unit" ? 1 + Math.sqrt(node.degree ?? 0) : 2 + Math.sqrt(node.degree ?? 0),
    })),
    source.edges
      .filter(
        (edge) =>
          layoutNodeIds.has(edge.from) &&
          layoutNodeIds.has(edge.to) &&
          (edge.kind === "cites" || edge.kind === "derived-from" || edge.kind === "prerequisite"),
      )
      .map((edge) => ({ a: edge.from, b: edge.to, weight: edge.kind === "prerequisite" ? 2.5 : 1 })),
    { iterations: 700, linkDistance: 160, charge: 6000, gravity: 0.002, seed: 0x51a7 },
  );
  for (const node of layoutNodes) {
    const point = layout.get(node.id);
    if (point) {
      node.x = round(point.x);
      node.y = round(point.y);
    }
  }

  // ------------------------------------------------------------------ statistics
  const count = <T extends string>(items: T[]) => {
    const map: Record<string, number> = {};
    for (const item of items) map[item] = (map[item] ?? 0) + 1;
    return map;
  };
  const subjectUnits = count(source.units.map((unit) => unit.subject));
  const sourceCiting = new Map<string, string[]>();
  for (const edge of source.edges) {
    if (edge.kind !== "cites") continue;
    const list = sourceCiting.get(edge.to) ?? [];
    list.push(edge.from);
    sourceCiting.set(edge.to, list);
  }
  const topSources = [...sourceCiting.entries()]
    .map(([sourceId, citing]) => {
      const node = source.nodes.find((item) => item.id === sourceId);
      const packs = new Set(
        citing
          .map((unitId) => source.nodes.find((item) => item.id === unitId)?.container)
          .filter((value): value is string => Boolean(value)),
      );
      return { id: sourceId, label: node?.label ?? sourceId, citations: citing.length, packs: packs.size };
    })
    .sort((a, b) => b.citations - a.citations || b.packs - a.packs)
    .slice(0, 10);

  const atlasPublic = getAtlasPublic();
  const reviewConcepts = [...editorial.concepts, ...extension.concepts, ...continuation.concepts].filter(
    (concept) => concept.editorialState !== "published",
  ).length;
  const reviewEdges = [...editorial.semanticEdges, ...extension.semanticEdges, ...continuation.semanticEdges].filter(
    (edge) => edge.editorialState !== "published",
  ).length;

  const stats: GraphStats = {
    nodes: count(source.nodes.map((node) => node.kind)),
    edges: count(edges.map((edge) => edge.kind)),
    edgeLayers: count(edges.map((edge) => edge.layer)),
    islands: Object.entries(islands)
      .map(([id, value]) => ({ id: Number(id), size: value.size, label: value.label, subjects: value.subjects }))
      .sort((a, b) => b.size - a.size || a.id - b.id),
    modularity: Number(analysis.modularity.toFixed(3)),
    clusters: analysis.clusters,
    components: analysis.componentCount,
    isolatedUnits: analysis.isolated.filter((id) => unitIds.has(id)).length,
    topHubs: [...source.units]
      .map((unit) => {
        const node = source.nodes.find((item) => item.id === unit.id)!;
        return { id: unit.id, label: unit.label, degree: node.degree ?? 0, kind: node.kind };
      })
      .sort((a, b) => b.degree - a.degree || (a.id < b.id ? -1 : 1))
      .slice(0, 12),
    candidatePairs: candidates.length,
    candidateSubjects: count(
      candidates.map((edge) => {
        const from = source.nodes.find((node) => node.id === edge.from);
        const to = source.nodes.find((node) => node.id === edge.to);
        return [from?.subject ?? "?", to?.subject ?? "?"].sort().join("↔");
      }),
    ),
    subjectUnits,
    topSources,
    atlas: {
      publishedConcepts: atlasPublic.concepts.length,
      publishedEdges: atlasPublic.semanticEdges.length,
      reviewConcepts,
      reviewEdges,
    },
  };

  const nodeIds = new Set(source.nodes.map((node) => node.id));
  for (const edge of edges) {
    if (!nodeIds.has(edge.from) || !nodeIds.has(edge.to)) {
      diagnostics.push({ level: "error", code: "dangling-edge", message: `${edge.id} has a missing endpoint` });
    }
  }
  const unitCount = source.units.length;
  if (stats.isolatedUnits > unitCount * 0.5) {
    diagnostics.push({
      level: "warning",
      code: "sparse-units",
      message: `${stats.isolatedUnits} of ${unitCount} units have no verified unit-to-unit link`,
    });
  }

  const graph: KnowledgeGraph = {
    version: "knowledge-graph-2026-11-06.2",
    generatedAt: new Date().toISOString(),
    nodes: source.nodes,
    edges,
    diagnostics,
    stats,
    islands,
  };
  cached = graph;
  return graph;
}

/**
 * Client payload: drop the analysis text and the pre-rendered evidence sentence
 * (the inspector rebuilds it from the pointer, shared sources or shared terms).
 * This keeps the static JSON small without losing provenance.
 */
export function clientGraph(graph: KnowledgeGraph) {
  return {
    ...graph,
    nodes: graph.nodes.map((node) => {
      const { text, ...rest } = node;
      void text;
      return rest;
    }),
    edges: graph.edges.map((edge) => {
      if (edge.kind === "co-citation") {
        return { from: edge.from, to: edge.to, kind: edge.kind, layer: edge.layer, weight: edge.weight, via: edge.via };
      }
      if (edge.kind === "lexical") {
        return { from: edge.from, to: edge.to, kind: edge.kind, layer: edge.layer, score: edge.score, terms: edge.terms };
      }
      return { from: edge.from, to: edge.to, kind: edge.kind, layer: edge.layer, weight: edge.weight, pointer: edge.pointer };
    }),
  };
}
