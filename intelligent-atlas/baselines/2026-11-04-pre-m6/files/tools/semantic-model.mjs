// Canonical concept registry, ambiguity register, contradiction register and
// typed relation candidates for the Hansa Intelligent Atlas.
//
// This file is DATA, not a runtime dependency. `analyze-corpus.mjs` resolves
// every `patterns` entry against the extracted unit ledger and every
// `evidence` selector against real unit text. A selector that matches nothing
// fails the build: no relation may exist without a verbatim corpus passage.
//
// Review state is always "candidate" here. Nothing in this file is approved or
// published. Existing Atlas identities are reused through `existing`, and the
// crosswalk layer records the mapping rather than creating parallel IDs.

