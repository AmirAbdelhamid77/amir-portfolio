// Word-boundary helper for Latin terms. Arabic is matched as a substring
// because JavaScript word boundaries do not treat Arabic letters as word
// characters.
const W = (source) => String.raw`\b(?:${source})\b`;

function concept(id, prefLabel, domain, kind, definition, opts = {}) {
  return {
    id,
    prefLabel,
    domain,
    kind,
    definition,
    scope: opts.scope ?? "",
    discriminatingContext: opts.context ?? "",
    aliases: { en: opts.en ?? [], ar: opts.ar ?? [] },
    patterns: opts.patterns ?? [],
    // Domain-scoped matching. Visualization concepts are validated against the
    // data-viz corpus, the SQL visualization lesson and the exam bank; matching
    // them against unrelated Fabric prose produced lexical false positives.
    matchFamilies: opts.families ?? (domain === "visualization" ? ["visualization", "sql", "exams"] : domain === "statistics" ? ["statistics", "visualization", "exams"] : []),
    packTags: opts.packTags ?? [],
    exclude: opts.exclude ?? [],
    existingAtlasId: opts.existing ?? null,
    sourceRefs: opts.sources ?? [],
    reviewState: "candidate",
  };
}

